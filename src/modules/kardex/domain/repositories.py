from typing import Protocol, Optional, List
from src.modules.kardex.domain.models import Cosecha, Movimiento


class CosechaRepository(Protocol):
    def list_all(self) -> List[Cosecha]: ...
    def get_by_id(self, cosecha_id: int) -> Optional[Cosecha]: ...
    def add(self, data) -> Cosecha: ...
    def total_kg_by_month(self, anio: int, mes: int) -> float: ...
    def editar(self, cosecha_id: int, data) -> Cosecha: ...
    def eliminar(self, cosecha_id: int) -> None: ...


class MovimientoRepository(Protocol):
    def list_all(self, finca_id: int | None = None, lote_id: int | None = None,
                 producto_id: int | None = None) -> List[Movimiento]: ...
    def add(self, data, usuario_id: int) -> Movimiento: ...
    def recibir(self, cosecha_id: int, data, usuario_id: int): ...
    def anular(self, movimiento_id: int, motivo: str, usuario_id: int) -> Movimiento: ...
